"""
Spectra MCP - Built-in Forward Interception Proxy Server
Listens on local port (default 8088) to transparently capture, audit, scope-check,
and cookie-inject outbound HTTP/HTTPS traffic generated by AI Agent custom scripts
(Python requests/httpx/urllib, curl, sqlmap, ffuf, nuclei).
"""

import os
import sys
import json
import time
import asyncio
import urllib.parse
from typing import Optional, Dict, Any, Tuple
import httpx

from backend.database import SessionLocal, HttpLog, Project, ActiveSession
from backend.intercept_manager import async_check_scope
from backend.analyzer import analyze_traffic
from backend.target_manager import auto_ingest_url_to_target_graph

_proxy_server: Optional[asyncio.Server] = None
_is_proxy_running: bool = False
_proxy_port: int = int(os.getenv("SPECTRA_PROXY_PORT", "8088"))
_proxy_host: str = os.getenv("SPECTRA_PROXY_HOST", "127.0.0.1")

def get_proxy_port() -> int:
    return _proxy_port

def get_proxy_url() -> str:
    return f"http://{_proxy_host}:{_proxy_port}"

def is_proxy_running() -> bool:
    return _is_proxy_running

_current_active_projects = []

class ProxyContext:
    """Context manager for associating the current active command/agent with proxy requests."""
    def __init__(self, project: str, agent_id: str = "primary_agent"):
        self.project = (project or "default").strip().lower()
        self.agent_id = agent_id or "primary_agent"

    def __enter__(self):
        _current_active_projects.append((self.project, self.agent_id))
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        if (self.project, self.agent_id) in _current_active_projects:
            _current_active_projects.remove((self.project, self.agent_id))

def get_current_active_context() -> Tuple[str, str]:
    if _current_active_projects:
        return _current_active_projects[-1]
    default_proj = os.getenv("SPECTRA_PROJECT", "default").strip().lower()
    return default_proj, "primary_agent"


def _get_active_cookies_for_host(host: str, project: str) -> Dict[str, str]:
    """Retrieves session cookies registered for the given target host."""
    cookies = {}
    try:
        db = SessionLocal()
        try:
            sessions = db.query(ActiveSession).filter(ActiveSession.is_active == True).all()
            target_host = host.split(":")[0].lower()
            for s in sessions:
                stored_dom = (s.domain or "").lower().split(":")[0].strip("/")
                is_match = (
                    target_host == stored_dom or
                    target_host.endswith("." + stored_dom) or
                    stored_dom.endswith("." + target_host) or
                    (stored_dom in target_host and len(stored_dom) > 3)
                )
                if is_match:
                    try:
                        state_data = s.get_decrypted_state()
                        for c in state_data.get("cookies", []):
                            cn = c.get("name")
                            cv = c.get("value")
                            if cn and cv:
                                cookies[cn] = cv
                    except Exception:
                        pass
        finally:
            db.close()
    except Exception:
        pass
    return cookies


async def _dispatch_log(log_payload: Dict[str, Any]):
    """Dispatches log to running backend API or commits directly to SQLite database."""
    backend_url = os.getenv("SPECTRA_BACKEND_URL", "http://127.0.0.1:8000").rstrip("/")
    try:
        async with httpx.AsyncClient(timeout=1.5) as client:
            resp = await client.post(f"{backend_url}/api/logs", json=log_payload)
            if resp.status_code == 200:
                return resp.json()
    except Exception:
        pass

    # Direct SQLite fallback if backend HTTP endpoint is not reachable
    db = SessionLocal()
    try:
        proj = (log_payload.get("project") or "default").strip().lower()
        if not db.query(Project).filter(Project.name == proj).first():
            db.add(Project(name=proj, description="Auto-created workspace"))
            db.commit()

        entry = HttpLog(
            project=proj,
            agent_id=log_payload.get("agent_id", "primary_agent") or "primary_agent",
            source=log_payload.get("source", "FORWARD_PROXY"),
            method=log_payload.get("method", "GET"),
            url=log_payload.get("url", ""),
            host=log_payload.get("host", ""),
            path=log_payload.get("path", "/"),
            status_code=log_payload.get("status_code"),
            duration_ms=log_payload.get("duration_ms", 0),
            request_headers=json.dumps(log_payload.get("request_headers", {})),
            request_body=(log_payload.get("request_body") or "")[:5242880],
            response_headers=json.dumps(log_payload.get("response_headers", {})),
            response_body=(log_payload.get("response_body") or "")[:5242880],
            reasoning=log_payload.get("reasoning", ""),
            flag_status="CLEAN"
        )
        flag, findings = analyze_traffic(entry)
        entry.flag_status = flag
        db.add(entry)
        db.commit()
        db.refresh(entry)

        try:
            auto_ingest_url_to_target_graph(proj, entry.url, entry.method)
        except Exception:
            pass

        return {"id": entry.id, "flag_status": flag, "findings": findings}
    except Exception:
        db.rollback()
        return None
    finally:
        db.close()


async def _handle_client_connection(reader: asyncio.StreamReader, writer: asyncio.StreamWriter):
    """Handles an incoming proxy connection from client."""
    try:
        # Read the initial request line (e.g. GET http://target/path HTTP/1.1 or CONNECT target:443 HTTP/1.1)
        line = await reader.readline()
        if not line:
            writer.close()
            return

        line_str = line.decode("utf-8", errors="replace").strip()
        parts = line_str.split()
        if len(parts) < 2:
            writer.close()
            return

        method = parts[0].upper()
        raw_url = parts[1]

        # Read remaining headers
        headers: Dict[str, str] = {}
        content_length = 0
        while True:
            hdr_line = await reader.readline()
            if not hdr_line or hdr_line == b"\r\n" or hdr_line == b"\n":
                break
            hdr_str = hdr_line.decode("utf-8", errors="replace").strip()
            if ":" in hdr_str:
                k, v = hdr_str.split(":", 1)
                headers[k.strip()] = v.strip()
                if k.strip().lower() == "content-length":
                    try:
                        content_length = int(v.strip())
                    except ValueError:
                        content_length = 0

        # Extract Project & Agent context
        ctx_proj, ctx_agent = get_current_active_context()
        target_project = headers.get("X-Spectra-Project") or ctx_proj
        target_agent = headers.get("X-Spectra-Agent") or ctx_agent

        # ----------------------------------------------------------------------
        # CASE 1: HTTPS CONNECT TUNNELING
        # ----------------------------------------------------------------------
        if method == "CONNECT":
            dest_host, dest_port_str = raw_url.split(":", 1) if ":" in raw_url else (raw_url, "443")
            dest_port = int(dest_port_str) if dest_port_str.isdigit() else 443
            tunnel_url = f"https://{dest_host}:{dest_port}/"

            # Scope & Guardrail check
            db = SessionLocal()
            try:
                is_allowed, block_reason = await async_check_scope(target_project, tunnel_url, db)
            finally:
                db.close()

            if not is_allowed:
                blocked_res = (
                    "HTTP/1.1 403 Forbidden\r\n"
                    "Content-Type: text/plain\r\n"
                    "X-Spectra-Blocked: Scope Guardrail\r\n"
                    "Connection: close\r\n\r\n"
                    f"[!] BLOCKED BY SPECTRA SCOPE GUARD: {block_reason}\r\n"
                )
                writer.write(blocked_res.encode("utf-8"))
                await writer.drain()
                writer.close()

                await _dispatch_log({
                    "project": target_project,
                    "agent_id": target_agent,
                    "source": "FORWARD_PROXY",
                    "method": "CONNECT",
                    "url": tunnel_url,
                    "host": dest_host,
                    "path": "/",
                    "status_code": 403,
                    "duration_ms": 0,
                    "request_headers": headers,
                    "request_body": "",
                    "response_headers": {"X-Spectra-Blocked": "1"},
                    "response_body": f"<BLOCKED BY SPECTRA SCOPE GUARD: {block_reason}>",
                    "reasoning": f"[Auto-Captured via Proxy] HTTPS Tunnel blocked: {block_reason}"
                })
                return

            # Establish remote connection to target server
            try:
                remote_reader, remote_writer = await asyncio.open_connection(dest_host, dest_port)
            except Exception as err:
                err_res = f"HTTP/1.1 502 Bad Gateway\r\nConnection: close\r\n\r\nCannot connect to {dest_host}:{dest_port}: {err}\r\n"
                writer.write(err_res.encode("utf-8"))
                await writer.drain()
                writer.close()
                return

            # Respond 200 Connection Established to client
            writer.write(b"HTTP/1.1 200 Connection Established\r\n\r\n")
            await writer.drain()

            start_t = time.time()
            bytes_up = 0
            bytes_down = 0

            async def pipe_client_to_remote():
                nonlocal bytes_up
                try:
                    while True:
                        data = await reader.read(65536)
                        if not data:
                            break
                        bytes_up += len(data)
                        remote_writer.write(data)
                        await remote_writer.drain()
                except Exception:
                    pass
                finally:
                    try:
                        remote_writer.close()
                    except Exception:
                        pass

            async def pipe_remote_to_client():
                nonlocal bytes_down
                try:
                    while True:
                        data = await remote_reader.read(65536)
                        if not data:
                            break
                        bytes_down += len(data)
                        writer.write(data)
                        await writer.drain()
                except Exception:
                    pass
                finally:
                    try:
                        writer.close()
                    except Exception:
                        pass

            await asyncio.gather(pipe_client_to_remote(), pipe_remote_to_client(), return_exceptions=True)
            duration_ms = int((time.time() - start_t) * 1000)

            # Record HTTPS tunnel session
            await _dispatch_log({
                "project": target_project,
                "agent_id": target_agent,
                "source": "FORWARD_PROXY",
                "method": "CONNECT",
                "url": tunnel_url,
                "host": dest_host,
                "path": f"/{dest_port}",
                "status_code": 200,
                "duration_ms": duration_ms,
                "request_headers": headers,
                "request_body": f"Tunnel opened ({bytes_up} bytes sent)",
                "response_headers": {"X-Spectra-Proxy": "HTTPS_TUNNEL"},
                "response_body": f"Tunnel closed ({bytes_down} bytes received in {duration_ms}ms)",
                "reasoning": f"[Auto-Captured via Proxy] HTTPS Tunnel to {dest_host}:{dest_port} ({bytes_up}B up / {bytes_down}B down)"
            })
            return

        # ----------------------------------------------------------------------
        # CASE 2: REGULAR HTTP PROXY REQUEST
        # ----------------------------------------------------------------------
        body_text = ""
        if content_length > 0:
            body_bytes = await reader.readexactly(content_length)
            body_text = body_bytes.decode("utf-8", errors="replace")

        # Resolve full target URL
        if raw_url.startswith("http://") or raw_url.startswith("https://"):
            full_url = raw_url
        else:
            host_hdr = headers.get("Host") or "unknown"
            full_url = f"http://{host_hdr}{raw_url}"

        parsed = urllib.parse.urlparse(full_url)
        target_host = parsed.netloc
        target_path = (parsed.path or "/") + (f"?{parsed.query}" if parsed.query else "")

        # Scope Check
        db = SessionLocal()
        try:
            is_allowed, block_reason = await async_check_scope(target_project, full_url, db)
        finally:
            db.close()

        if not is_allowed:
            blocked_res = (
                "HTTP/1.1 403 Forbidden\r\n"
                "Content-Type: text/plain\r\n"
                "X-Spectra-Blocked: Scope Guardrail\r\n"
                "Connection: close\r\n\r\n"
                f"[!] BLOCKED BY SPECTRA SCOPE GUARD: {block_reason}\r\n"
            )
            writer.write(blocked_res.encode("utf-8"))
            await writer.drain()
            writer.close()

            await _dispatch_log({
                "project": target_project,
                "agent_id": target_agent,
                "source": "FORWARD_PROXY",
                "method": method,
                "url": full_url,
                "host": target_host,
                "path": target_path,
                "status_code": 403,
                "duration_ms": 0,
                "request_headers": headers,
                "request_body": body_text,
                "response_headers": {"X-Spectra-Blocked": "1"},
                "response_body": f"<BLOCKED BY SPECTRA SCOPE GUARD: {block_reason}>",
                "reasoning": f"[Auto-Captured via Proxy] Out of scope: {block_reason}"
            })
            return

        # Auto-Inject Active Session Cookies
        active_cookies = _get_active_cookies_for_host(target_host, target_project)
        fwd_headers = dict(headers)
        # Remove hop-by-hop headers
        for hop in ["proxy-connection", "proxy-authorization", "keep-alive"]:
            fwd_headers.pop(hop, None)
            fwd_headers.pop(hop.title(), None)

        if active_cookies:
            existing_cookie = fwd_headers.get("Cookie") or fwd_headers.get("cookie") or ""
            cookie_parts = [c.strip() for c in existing_cookie.split(";") if c.strip()]
            existing_keys = {c.split("=")[0].strip() for c in cookie_parts if "=" in c}
            for ck, cv in active_cookies.items():
                if ck not in existing_keys:
                    cookie_parts.append(f"{ck}={cv}")
            fwd_headers["Cookie"] = "; ".join(cookie_parts)

        # Forward request to actual target server
        start_t = time.time()
        status_code = 502
        res_headers: Dict[str, str] = {}
        res_body_text = ""

        try:
            async with httpx.AsyncClient(verify=False, follow_redirects=False, timeout=30.0) as client:
                res = await client.request(
                    method=method,
                    url=full_url,
                    headers=fwd_headers,
                    content=body_text.encode("utf-8") if body_text else None
                )
                status_code = res.status_code
                res_headers = dict(res.headers)
                try:
                    res_body_text = res.text
                except Exception:
                    res_body_text = f"<Binary response: {len(res.content)} bytes>"
                res_bytes = res.content
        except Exception as ex:
            status_code = 502
            res_body_text = f"Gateway Connection Error: {str(ex)}"
            res_bytes = res_body_text.encode("utf-8")

        duration_ms = int((time.time() - start_t) * 1000)

        # Build response to client
        reason_phrase = "OK" if status_code == 200 else "Response"
        res_line = f"HTTP/1.1 {status_code} {reason_phrase}\r\n"
        writer.write(res_line.encode("utf-8"))
        for hk, hv in res_headers.items():
            if hk.lower() not in ["transfer-encoding"]:
                writer.write(f"{hk}: {hv}\r\n".encode("utf-8"))
        writer.write(f"Content-Length: {len(res_bytes)}\r\n\r\n".encode("utf-8"))
        writer.write(res_bytes)
        await writer.drain()
        writer.close()

        # Log transaction to Spectra
        await _dispatch_log({
            "project": target_project,
            "agent_id": target_agent,
            "source": "FORWARD_PROXY",
            "method": method,
            "url": full_url,
            "host": target_host,
            "path": target_path,
            "status_code": status_code,
            "duration_ms": duration_ms,
            "request_headers": fwd_headers,
            "request_body": body_text,
            "response_headers": res_headers,
            "response_body": res_body_text,
            "reasoning": f"[Auto-Captured from Script via Spectra Proxy] {method} {target_path}"
        })

    except Exception:
        try:
            writer.close()
        except Exception:
            pass


async def start_forward_proxy(host: Optional[str] = None, port: Optional[int] = None) -> asyncio.Server:
    """Starts the Spectra Forward Proxy server asynchronously."""
    global _proxy_server, _is_proxy_running, _proxy_host, _proxy_port
    if _is_proxy_running and _proxy_server:
        return _proxy_server

    _proxy_host = host or os.getenv("SPECTRA_PROXY_HOST", "127.0.0.1")
    _proxy_port = port or int(os.getenv("SPECTRA_PROXY_PORT", "8088"))

    _proxy_server = await asyncio.start_server(_handle_client_connection, _proxy_host, _proxy_port)
    _is_proxy_running = True
    return _proxy_server


async def stop_forward_proxy():
    """Stops the Spectra Forward Proxy server."""
    global _proxy_server, _is_proxy_running
    if _proxy_server:
        _proxy_server.close()
        await _proxy_server.wait_closed()
        _proxy_server = None
    _is_proxy_running = False
